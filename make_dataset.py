def build(templates, label, n):
    out = set()
    tries = 0
    while len(out) < n and tries < n * 20:
        tries += 1
        t = fill(pick(templates).replace("@{w}", "@" + pick(WORDS) + str(random.randint(1, 99))))
        t = " ".join(t.split())
        if label != "ok":
            t = obfuscate(t)
        out.add(t)
    return [(t, label) for t in out]


