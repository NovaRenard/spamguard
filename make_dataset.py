def obfuscate(t: str) -> str:
    r = random.random()
    words = t.split()
    cand = [i for i, w in enumerate(words) if len(w) >= 5]
    if not cand or r > 0.25:
        return t
    i = pick(cand)
    words[i] = " ".join(words[i]) if r < 0.1 else words[i].translate(HOMO)
    return " ".join(words)


